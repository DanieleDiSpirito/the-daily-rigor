/* Builds supabase/catalog.sql: the library as the database needs to know it to compute the scoreboard
   (see compute_stats in supabase/schema.sql). Regenerate it with `npm run gen:catalog` whenever content
   changes; `npm run test:content` fails if the committed file is out of date. */
import { codingProblems } from '../src/content/code';
import { mathPuzzles } from '../src/content/math';
import { papers } from '../src/content/papers';
import { EPOCH } from '../src/lib/daily';
import { DIFFICULTY_WEIGHT } from '../src/lib/scoring';

/** The time zone in which the day changes (DAY_TZ on the server, Europe/Rome by default). */
const ZONE = process.env.DAY_TZ || 'Europe/Rome';
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function buildCatalogSql(): string {
  const rows: string[] = [];
  const add = (section: string, list: { id: string; value: number; cats: string[] }[]) =>
    list.forEach((x, pos) => rows.push(`  (${q(section)}, ${q(x.id)}, ${pos}, ${x.value}, array[${x.cats.map(q).join(', ')}])`));
  add('math', mathPuzzles.map((x) => ({ id: x.id, value: DIFFICULTY_WEIGHT[x.difficulty], cats: x.topic.split(' · ') })));
  add('code', codingProblems.map((x) => ({ id: x.id, value: x.rating, cats: x.tags })));
  add('papers', papers.map((x) => ({ id: x.id, value: x.readingMinutes, cats: x.topics })));
  const epoch = new Date(EPOCH).toISOString().slice(0, 10);
  return `-- GENERATED by \`npm run gen:catalog\` from src/content: do not edit by hand.
-- Run it in the Supabase SQL Editor (safe to run again) whenever the library changes, so that the scoreboard
-- knows the new items. The order of the rows is the order of the daily rotation.

create table if not exists public.catalog (
  section text not null,
  item_id text not null,
  pos     int  not null,
  value   numeric not null, -- difficulty weight, rating or reading minutes: what the item is worth in its feature
  cats    text[] not null,
  primary key (section, item_id)
);
alter table public.catalog enable row level security; -- no policies: only the scoreboard function reads it

create or replace function public.launch_epoch() returns date language sql immutable as $$ select date ${q(epoch)} $$;
create or replace function public.day_zone() returns text language sql immutable as $$ select ${q(ZONE)}::text $$;

truncate public.catalog;
insert into public.catalog (section, item_id, pos, value, cats) values
${rows.join(',\n')};
`;
}
